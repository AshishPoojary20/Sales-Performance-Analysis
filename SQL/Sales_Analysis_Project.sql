-- =============================================
-- PROJECT: SALES PERFORMANCE ANALYSIS
-- DATABASE: SalesAnalysis
-- TABLE: dbo.SalesData
-- TOOL: SQL Server
-- =============================================

-- 1: VERIFY DATABASE

USE SalesAnalysis;
GO

-- Check whether the sales table exists

SELECT TOP 10 *
FROM dbo.SalesData;
GO

ALTER TABLE dbo.SalesData
ADD PRICEEACH_CLEAN DECIMAL(18,2);
GO

UPDATE dbo.SalesData
SET PRICEEACH_CLEAN = CAST(PRICEEACH AS DECIMAL(18,2));
GO

SELECT TOP 10
    PRICEEACH,
    PRICEEACH_CLEAN,
    SALES,
    SALES_CLEAN
FROM dbo.SalesData;
GO

-- 2: VERIFY CLEANED DATA

SELECT TOP 10
    ORDERNUMBER,
    PRODUCTCODE,
    PRICEEACH,
    PRICEEACH_CLEAN,
    SALES,
    SALES_CLEAN,
    ORDERDATE,
    ORDERDATE_CLEAN
FROM dbo.SalesData;
GO


-- 3: DATA QUALITY CHECK

SELECT
    COUNT(*) AS TotalRecords,
    COUNT(DISTINCT ORDERNUMBER) AS UniqueOrders,
    COUNT(DISTINCT CUSTOMERNAME) AS UniqueCustomers,
    COUNT(DISTINCT COUNTRY) AS UniqueCountries,
    COUNT(DISTINCT PRODUCTLINE) AS ProductLines,

    SUM(CASE
        WHEN SALES_CLEAN IS NULL THEN 1
        ELSE 0
    END) AS MissingSales,

    SUM(CASE
        WHEN ORDERDATE_CLEAN IS NULL THEN 1
        ELSE 0
    END) AS MissingDates,

    MIN(ORDERDATE_CLEAN) AS FirstOrderDate,
    MAX(ORDERDATE_CLEAN) AS LastOrderDate,

    SUM(SALES_CLEAN) AS TotalSales

FROM dbo.SalesData;
GO


-- 4: SALES BY PRODUCT LINE


SELECT
    PRODUCTLINE,
    COUNT(*) AS TotalRecords,
    SUM(SALES_CLEAN) AS TotalSales,
    AVG(SALES_CLEAN) AS AverageSales
FROM dbo.SalesData
GROUP BY PRODUCTLINE
ORDER BY TotalSales DESC;
GO


-- 5: COUNTRY-WISE SALES ANALYSIS

SELECT
    COUNTRY,
    COUNT(DISTINCT ORDERNUMBER) AS TotalOrders,
    SUM(SALES_CLEAN) AS TotalSales
FROM dbo.SalesData
GROUP BY COUNTRY
ORDER BY TotalSales DESC;
GO


-- 6: YEARLY SALES ANALYSIS

SELECT
    YEAR(ORDERDATE_CLEAN) AS SalesYear,
    COUNT(DISTINCT ORDERNUMBER) AS TotalOrders,
    SUM(SALES_CLEAN) AS TotalSales
FROM dbo.SalesData
GROUP BY YEAR(ORDERDATE_CLEAN)
ORDER BY SalesYear;
GO


-- 7: MONTHLY SALES ANALYSIS

SELECT
    YEAR(ORDERDATE_CLEAN) AS SalesYear,
    MONTH(ORDERDATE_CLEAN) AS SalesMonth,
    DATENAME(MONTH, ORDERDATE_CLEAN) AS MonthName,
    SUM(SALES_CLEAN) AS TotalSales
FROM dbo.SalesData
GROUP BY
    YEAR(ORDERDATE_CLEAN),
    MONTH(ORDERDATE_CLEAN),
    DATENAME(MONTH, ORDERDATE_CLEAN)
ORDER BY
    SalesYear,
    SalesMonth;
GO

-- 8: ORDER STATUS ANALYSIS

SELECT
    STATUS,
    COUNT(DISTINCT ORDERNUMBER) AS TotalOrders,
    SUM(SALES_CLEAN) AS TotalSales
FROM dbo.SalesData
GROUP BY STATUS
ORDER BY TotalOrders DESC;
GO


-- 9: TOP 10 CUSTOMER ANALYSIS

SELECT TOP 10
    CUSTOMERNAME,
    COUNT(DISTINCT ORDERNUMBER) AS TotalOrders,
    SUM(SALES_CLEAN) AS TotalSales
FROM dbo.SalesData
GROUP BY CUSTOMERNAME
ORDER BY TotalSales DESC;
GO


-- 10: TOP 10 PRODUCT ANALYSIS

SELECT TOP 10
    PRODUCTCODE,
    PRODUCTLINE,
    SUM(QUANTITYORDERED) AS TotalQuantity,
    SUM(SALES_CLEAN) AS TotalSales
FROM dbo.SalesData
GROUP BY
    PRODUCTCODE,
    PRODUCTLINE
ORDER BY
    TotalSales DESC;
GO



-- 11: CREATE CLEAN REPORTING VIEW

CREATE OR ALTER VIEW dbo.vw_SalesAnalysis
AS
SELECT
    ORDERNUMBER,
    QUANTITYORDERED,
    PRICEEACH_CLEAN AS PRICEEACH,
    ORDERLINENUMBER,
    SALES_CLEAN AS SALES,
    ORDERDATE_CLEAN AS ORDERDATE,
    STATUS,
    QTR_ID,
    MONTH_ID,
    YEAR_ID,
    PRODUCTLINE,
    MSRP,
    PRODUCTCODE,
    CUSTOMERNAME,
    PHONE,
    ADDRESSLINE1,
    ADDRESSLINE2,
    CITY,
    STATE,
    POSTALCODE,
    COUNTRY,
    TERRITORY,
    CONTACTLASTNAME,
    CONTACTFIRSTNAME,
    DEALSIZE
FROM dbo.SalesData;
GO

-- Verify Reporting view

SELECT TOP 10 *
FROM dbo.vw_SalesAnalysis;
GO

-- 12: FINAL REPORTING VIEW VALIDATION

SELECT
    COUNT(*) AS TotalRecords,
    COUNT(DISTINCT ORDERNUMBER) AS UniqueOrders,
    COUNT(DISTINCT CUSTOMERNAME) AS UniqueCustomers,
    COUNT(DISTINCT COUNTRY) AS UniqueCountries,
    SUM(SALES) AS TotalSales,
    MIN(ORDERDATE) AS FirstOrderDate,
    MAX(ORDERDATE) AS LastOrderDate
FROM dbo.vw_SalesAnalysis;
GO

SELECT TOP 10
    PRODUCTCODE,
    PRODUCTLINE,
    SUM(QUANTITYORDERED) AS TotalUnitsSold,
    SUM(SALES_CLEAN) AS TotalSales
FROM dbo.SalesData
GROUP BY PRODUCTCODE, PRODUCTLINE
ORDER BY TotalSales DESC;